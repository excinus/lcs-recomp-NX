#!/usr/bin/env python3
"""Rasterizes the Cheat Device overlay font (cdr_font.hpp).

DejaVu Sans Bold, Latin-1 (32-255), anti-aliased, one alpha byte per pixel.
Run: python3 make_font.py /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf > ../cdr_font.hpp
"""
import sys
from PIL import Image, ImageDraw, ImageFont

PIXEL_SIZE = 22  # the cap-to-descender size the menu's scale 1.0 maps to (960x544 overlay)
font = ImageFont.truetype(sys.argv[1], PIXEL_SIZE)
ascent, descent = font.getmetrics()
line = ascent + descent
glyphs = []
data = []
for code in range(32, 256):
    ch = chr(code)
    if 127 <= code < 160:
        glyphs.append((0, 0, 0, 0, 0, len(data)))
        continue
    left, top, right, bottom = font.getbbox(ch)
    advance = int(round(font.getlength(ch)))
    width, height = max(0, right - left), max(0, bottom - top)
    offset = len(data)
    if width and height:
        image = Image.new('L', (width, height), 0)
        ImageDraw.Draw(image).text((-left, -top), ch, font=font, fill=255)
        data.extend(image.tobytes())
    glyphs.append((advance, left, top, width, height, offset))
print('// Generated by tools/make_font.py from DejaVu Sans Bold. Do not edit.')
print('//')
print('// DejaVu fonts: Copyright (c) 2003 by Bitstream, Inc. (Bitstream Vera, all rights')
print('// reserved; DejaVu changes are in the public domain). The license permits')
print('// embedding the glyphs; see https://dejavu-fonts.github.io/License.html')
print('#pragma once')
print('#include <cstdint>')
print('namespace cdr_font {')
print(f'inline constexpr int kLineHeight = {line};')
print(f'inline constexpr int kAscent = {ascent};')
print('struct Glyph { std::uint8_t advance; std::int8_t left; std::int8_t top; std::uint8_t width; std::uint8_t height; std::uint32_t offset; };')
print('// Characters 32..255 (Latin-1).')
print('inline constexpr Glyph kGlyphs[224] = {')
for g in glyphs:
    print('    {%d, %d, %d, %d, %d, %d},' % g)
print('};')
print(f'inline constexpr std::uint8_t kAlpha[{len(data)}] = {{')
for i in range(0, len(data), 32):
    print('    ' + ','.join(str(b) for b in data[i:i+32]) + ',')
print('};')
print('}  // namespace cdr_font')
